#!/usr/bin/env bash
# Reproducibly vendors the C core used by the iOS app.
#
# Sources are read from pinned git objects, never from the working tree:
#   libfuji  = this repository at LIBFUJI_SHA   (lib/, fp/src/)
#   libpict  = submodule libpict at LIBPICT_SHA (src/)
# Then the patches in ios/patches/<lib>/*.patch are applied in order.
#
# Usage:
#   ios/scripts/vendor-sync.sh           # regenerate ios/FujiKit/Sources/CFujiCore/upstream
#   ios/scripts/vendor-sync.sh --check   # verify the committed copy matches pinned sources + patches
#   ios/scripts/vendor-sync.sh --pristine DIR  # write unpatched copies to DIR (for making new patches)
set -euo pipefail

LIBFUJI_SHA=90aaa9319ef84711ef584fb4440d6e0d2511f662
LIBPICT_SHA=2e973f0336a2a58d749496ae9bd3795f12228241

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DEST="$ROOT/ios/FujiKit/Sources/CFujiCore/upstream"
PATCHES="$ROOT/ios/patches"

# "<git-dir-relative-to-ROOT>|<sha>|<source path>|<vendored path>"
FILES=(
	".|$LIBFUJI_SHA|lib/fuji.c|libfuji/fuji.c"
	".|$LIBFUJI_SHA|lib/fuji.h|libfuji/fuji.h"
	".|$LIBFUJI_SHA|lib/fujiptp.h|libfuji/fujiptp.h"
	".|$LIBFUJI_SHA|lib/app.h|libfuji/app.h"
	".|$LIBFUJI_SHA|lib/data.c|libfuji/fuji_data.c"
	".|$LIBFUJI_SHA|lib/exif.c|libfuji/exif.c"
	".|$LIBFUJI_SHA|lib/exif.h|libfuji/exif.h"
	".|$LIBFUJI_SHA|lib/fuji_usb.c|libfuji/fuji_usb.c"
	".|$LIBFUJI_SHA|lib/discovery.c|libfuji/discovery.c"
	".|$LIBFUJI_SHA|LICENSE|libfuji/LICENSE"
	".|$LIBFUJI_SHA|fp/src/fp.h|fp/fp.h"
	".|$LIBFUJI_SHA|fp/src/d185.c|fp/d185.c"
	".|$LIBFUJI_SHA|fp/src/data.c|fp/fp_data.c"
	".|$LIBFUJI_SHA|fp/src/xml.c|fp/xml.c"
	".|$LIBFUJI_SHA|fp/src/ezxml.c|fp/ezxml.c"
	".|$LIBFUJI_SHA|fp/src/ezxml.h|fp/ezxml.h"
	"libpict|$LIBPICT_SHA|LICENSE|libpict/LICENSE"
	"libpict|$LIBPICT_SHA|src/libpict.h|libpict/libpict.h"
	"libpict|$LIBPICT_SHA|src/ptp.h|libpict/ptp.h"
	"libpict|$LIBPICT_SHA|src/cl_backend.h|libpict/cl_backend.h"
	"libpict|$LIBPICT_SHA|src/cl_bind.h|libpict/cl_bind.h"
	"libpict|$LIBPICT_SHA|src/cl_data.h|libpict/cl_data.h"
	"libpict|$LIBPICT_SHA|src/cl_enum.h|libpict/cl_enum.h"
	"libpict|$LIBPICT_SHA|src/cl_ops.h|libpict/cl_ops.h"
	"libpict|$LIBPICT_SHA|src/cl_stuff.h|libpict/cl_stuff.h"
	"libpict|$LIBPICT_SHA|src/mutex_err.h|libpict/mutex_err.h"
	"libpict|$LIBPICT_SHA|src/lib.c|libpict/lib.c"
	"libpict|$LIBPICT_SHA|src/operations.c|libpict/operations.c"
	"libpict|$LIBPICT_SHA|src/packet.c|libpict/packet.c"
	"libpict|$LIBPICT_SHA|src/data.c|libpict/pict_data.c"
	"libpict|$LIBPICT_SHA|src/transport.c|libpict/transport.c"
	"libpict|$LIBPICT_SHA|src/ip.c|libpict/ip.c"
	"libpict|$LIBPICT_SHA|src/enums.c|libpict/enums.c"
	"libpict|$LIBPICT_SHA|src/enum_dump.c|libpict/enum_dump.c"
	"libpict|$LIBPICT_SHA|src/conv.c|libpict/conv.c"
	"libpict|$LIBPICT_SHA|src/generic.c|libpict/generic.c"
	"libpict|$LIBPICT_SHA|src/liveview.c|libpict/liveview.c"
	"libpict|$LIBPICT_SHA|src/canon.c|libpict/canon.c"
	"libpict|$LIBPICT_SHA|src/ml.c|libpict/ml.c"
)

ensure_libpict() {
	if ! git -C "$ROOT/libpict" cat-file -e "$LIBPICT_SHA^{commit}" 2>/dev/null; then
		echo "libpict $LIBPICT_SHA not available, initialising submodule over HTTPS" >&2
		# .gitmodules uses an SSH URL; rewrite to HTTPS for this command only.
		git -C "$ROOT" -c url."https://github.com/".insteadOf="git@github.com:" \
			submodule update --init libpict
	fi
}

write_pristine() {
	local out="$1"
	rm -rf "$out"
	mkdir -p "$out"
	for entry in "${FILES[@]}"; do
		IFS='|' read -r repo sha src dst <<<"$entry"
		mkdir -p "$out/$(dirname "$dst")"
		git -C "$ROOT/$repo" show "$sha:$src" >"$out/$dst"
	done
}

apply_patches() {
	local out="$1"
	local p
	shopt -s nullglob
	for p in "$PATCHES"/*/*.patch; do
		echo "applying ${p#"$ROOT"/}" >&2
		patch --quiet --forward --batch -p1 -d "$out" <"$p"
	done
	shopt -u nullglob
}

write_manifest() {
	local out="$1"
	{
		echo "# Generated by ios/scripts/vendor-sync.sh - do not edit."
		echo "libfuji $LIBFUJI_SHA"
		echo "libpict $LIBPICT_SHA"
		echo "# sha256 of vendored (patched) files"
		(cd "$out" && find . -type f ! -name VENDOR_MANIFEST.txt | LC_ALL=C sort | xargs sha256sum)
	} >"$out/VENDOR_MANIFEST.txt"
}

ensure_libpict

case "${1:-}" in
--pristine)
	write_pristine "${2:?directory required}"
	;;
--check)
	tmp="$(mktemp -d)"
	trap 'rm -rf "$tmp"' EXIT
	write_pristine "$tmp/upstream"
	apply_patches "$tmp/upstream"
	write_manifest "$tmp/upstream"
	if diff -r "$tmp/upstream" "$DEST" >/dev/null; then
		echo "OK: vendored C core matches pinned upstream + patches"
	else
		diff -ru "$tmp/upstream" "$DEST" | head -50
		echo "MISMATCH: run ios/scripts/vendor-sync.sh" >&2
		exit 1
	fi
	;;
"")
	tmp="$(mktemp -d)"
	trap 'rm -rf "$tmp"' EXIT
	write_pristine "$tmp/upstream"
	apply_patches "$tmp/upstream"
	write_manifest "$tmp/upstream"
	rm -rf "$DEST"
	mkdir -p "$(dirname "$DEST")"
	cp -R "$tmp/upstream" "$DEST"
	echo "vendored into ${DEST#"$ROOT"/}"
	;;
*)
	echo "unknown option $1" >&2
	exit 2
	;;
esac
